assert.equal(guide.productVersion,result.control.Version,'Delivery guide does not match this binary');
const report=['oss','onboarding','linux-deb','release'].map(prefix=>`validation/${prefix}-${result.control.Version}/REPORT.md`).find(file=>fs.existsSync(new URL('../../'+file,import.meta.url)));
