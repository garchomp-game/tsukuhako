import { test, expect } from '@playwright/test';
test('画面から保存・更新・再読込・削除を行う', async ({ page }) => {
  const body = `ブラウザ試験 ${Date.now()}`;
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'ローカル学習メモ' })).toBeVisible();
  await page.getByLabel('本文', { exact: true }).fill(`　${body}　`);
  await page.getByRole('button', { name: '保存する', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('保存しました');
  const row = page.locator('li').filter({ has: page.getByText(body, { exact: true }) });
  await expect(row).toBeVisible();
  await row.getByRole('button', { name: `編集: ${body}`, exact: true }).click();
  await page.getByLabel('本文', { exact: true }).fill(`${body} 更新📝`);
  await page.getByRole('button', { name: '更新する', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('更新しました');
  await page.reload();
  const updated = page.locator('li').filter({ has: page.getByText(`${body} 更新📝`, { exact: true }) });
  await expect(updated).toBeVisible();
  await page.screenshot({ path: 'test-results/notes-desktop.png', fullPage: true });
  await updated.getByRole('button', { name: `削除: ${body} 更新📝`, exact: true }).click();
  await expect(updated).toHaveCount(0);
  await page.reload();
  await expect(page.getByText(`${body} 更新📝`, { exact: true })).toHaveCount(0);
});
test('不正入力・通信障害・テキスト表示を確認する', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '保存する', exact: true }).click();
  await expect(page.getByRole('alert', { name: '操作エラー' })).toContainText('1文字以上');
  await page.getByLabel('本文', { exact: true }).fill('📝'.repeat(201));
  await page.getByRole('button', { name: '保存する', exact: true }).click();
  await expect(page.getByRole('alert', { name: '操作エラー' })).toContainText('200文字以内');
  const literal = '<script>window.__s2Executed=true</script>';
  await page.getByLabel('本文', { exact: true }).fill(literal);
  await page.getByRole('button', { name: '保存する', exact: true }).click();
  await expect(page.getByText(literal, { exact: true })).toBeVisible();
  expect(await page.evaluate(() => '__s2Executed' in window)).toBe(false);
  await page.getByRole('button', { name: `削除: ${literal}`, exact: true }).click();
  await expect(page.getByText(literal, { exact: true })).toHaveCount(0);
  await page.route('**/api/notes', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await page.getByLabel('本文', { exact: true }).fill('通信試験');
  await page.getByRole('button', { name: '保存する', exact: true }).click();
  await expect(page.getByRole('alert', { name: '操作エラー' })).toContainText('通信できません');
});
